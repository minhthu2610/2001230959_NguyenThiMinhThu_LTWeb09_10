CREATE DATABASE QL_BOOKSTORE
GO
USE QL_BOOKSTORE
GO
CREATE TABLE TACGIA
(
	MATG INT PRIMARY KEY,
	TENTG NVARCHAR(100),
	DIACHI NVARCHAR(100),
	TIEUSU NVARCHAR(100),
	DIENTHOAI VARCHAR(20),
)
CREATE TABLE NHAXUATBAN
(
	MANXB INT PRIMARY KEY,
	TENNXH NVARCHAR(100),
	DIACHI NVARCHAR(100),
	DIENTHOAI VARCHAR(20),
)
CREATE TABLE CHUDE
(
	MACD INT PRIMARY KEY,
	TENCHUDE NVARCHAR(100)
)
CREATE TABLE SACH
(
	MASACH INT PRIMARY KEY,
	TENSACH NVARCHAR(100),
	GIABAN DECIMAL,
	MOTA NTEXT,
	ANHBIA NVARCHAR(100),
	NGAYCAPNHAT DATETIME,
	SOLUONGBAN INT,
	MACD INT,
	MANXB INT,
	MOI BIT,
	FOREIGN KEY (MACD) REFERENCES CHUDE(MACD),
	FOREIGN KEY (MANXB) REFERENCES NHAXUATBAN(MANXB)
)
CREATE TABLE THAMGIA
(
	MATG INT,
	MASACH INT,
	VAITRO NVARCHAR(50),
	VITRI INT,
	PRIMARY KEY (MATG, MASACH),
	FOREIGN KEY (MATG) REFERENCES TACGIA(MATG),
	FOREIGN KEY (MASACH) REFERENCES SACH(MASACH),
)
CREATE TABLE KHACHHANG
(
	MAKH INT PRIMARY KEY,
	HOTEN NVARCHAR(100),
	TAIKHOAN NVARCHAR(100),
	MATKHAU VARCHAR(100),
	EMAIL VARCHAR(100),
	DIACHI NVARCHAR(100),
	DIENTHOAI VARCHAR(20),
	NGAYSINH DATE
)
CREATE TABLE DONDATHANG
(
	MADONHANG INT PRIMARY KEY,
	DATHANHTOAN BIT,
	TINHTRANGGIAOHANG NVARCHAR(100),
	NGAYDAT DATE,
	NGAYGIAO DATE,
	MAKH INT,
	FOREIGN KEY (MAKH) REFERENCES KHACHHANG(MAKH)
)
CREATE TABLE CHITIETDONHANG
(
	MADONHANG INT,
	MASACH INT,
	SOLUONG INT,
	DONGIA DECIMAL,
	PRIMARY KEY(MADONHANG, MASACH),
	FOREIGN KEY (MADONHANG) REFERENCES DONDATHANG(MADONHANG),
	FOREIGN KEY (MASACH) REFERENCES SACH(MASACH),
)
